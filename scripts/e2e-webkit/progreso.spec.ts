  await jf.ver('Apunta tus pasos de hoy')
  await jf.pulsar('Apunta tus pasos de hoy')
  await jf.ver('Últimos 7 días')
  await jf.noVer(DE_ANDROID)
  await jf.ver('mira los de Salud')
  await jf.revisar('Pasos')
  await jf.page.locator('[aria-label="Pasos"] button[aria-label="Más"]').first().tap()
  await jf.page.locator('[aria-label="Pasos"] button[aria-label="Más"]').first().tap()
  await jf.pulsar('Guardar pasos')
  await jf.ver('Pasos guardados · hoy: 1000')
  await jf.pulsar('+ Trote / carrera')
  await jf.revisar('hoja trote')
  await jf.pulsar('Añadir', '.sheet')
  await jf.ver('Añadido: trote')
  const hoy = (await jf.tabla<{ fecha: string; pasos: number; fuente: string }>('pasos')).find(p => p.fecha === '2026-10-13')!
