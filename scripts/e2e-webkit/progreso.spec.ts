test('fotos de progreso: hacer foto o elegirla de Fotos', async ({ page, jf }) => {
  await jf.deCero('2026-10-14T18:00:00')
  await jf.alta()
  await jf.pestana('Progreso')
  await jf.seg('Fotos')
  const elegir = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: /Hacer la primera foto/ }).tap()
  const fc = await elegir
  // En iPhone sin «capture»: así sale el menú «Hacer foto · Fototeca · Elegir archivo».
  expect(await fc.element().getAttribute('capture')).toBeNull()
  expect(await fc.element().getAttribute('accept')).toBe('image/*')
  await fc.setFiles(path.join(RAIZ, 'public', 'iconos', 'icono-512.png'))
  await jf.ver('Foto guardada', 8000)
  // Otra, unas semanas después: sale el comparador.
  await jf.irA('2026-11-11T18:00:00')
  await jf.pestana('Progreso')
  await jf.seg('Fotos')
  const otra = page.waitForEvent('filechooser')
  await jf.pulsar(/^Foto/)
  await (await otra).setFiles(path.join(RAIZ, 'public', 'iconos', 'icono-192.png'))
  await jf.ver('Foto guardada', 8000)
  await jf.ver(/Comparador/i)
  await jf.revisar('Fotos')
  expect(await jf.tabla('fotos')).toHaveLength(2)
  // Cerrar el selector sin elegir no deja nada a medias.
  const nada = page.waitForEvent('filechooser')
  await jf.pulsar(/^Foto/)
  await nada
  await page.evaluate(() => document.querySelector('input[type=file]')?.dispatchEvent(new Event('cancel')))
  await expect(page.locator('input[type=file]')).toHaveCount(0)
})

