// Generador v2: escenarios de extremo a extremo (se registran con escenario() y los pasa correr.mjs).
import { alta, comprobar, escenario, deCero, esperar, js, meter, perfilBD, pestana, pulsar, recargar, revisarAqui, t, tabla, ver } from '../ayudantes.mjs'

escenario('en orden: «Te toca», sesión mínima, «Me encuentro mal» y Mi plan con la cola', async () => {
  await deCero('2026-10-13T05:20:00') // martes
  await alta({ cola: true })
  comprobar((await perfilBD()).modoRutina === 'cola', 'Un alta nueva no va en orden')
  await ver('1.ª de 3 esta semana')
  await ver('Ver la cola')
  await revisarAqui('inicio en cola')
  // Sesión mínima desde la tarjeta: la hoja «Empezar» sale con «Mínima» marcada.
  await pulsar(/Sesión mínima de 15 min/)
  await ver('Mínima')
  await pulsar(/^Empezar$/, '.sheet')
  await ver('Hecho', 8000)
  const [s] = (await tabla('sesiones')).filter(x => x.estado === 'curso')
  comprobar(s?.version === 'minima' && s.ejercicios.length <= 4, 'La sesión mínima no se crea: ' + JSON.stringify([s?.version, s?.ejercicios.length]))
  // «Me encuentro mal» con una señal: para el entreno y no propone rutina hasta desmarcarlo.
  await t('pulsarSel', '[aria-label="Herramientas"]')
  await pulsar('Me encuentro mal', '.sheet')
  await ver('¿Te pasa algo de esto?')
  await pulsar('Mareo o desmayo', '.sheet')
  await pulsar('Parar el entreno', '.sheet')
  await ver('Hoy no entrenes')
  comprobar(!(await tabla('sesiones')).some(x => x.estado === 'curso'), 'El entreno sigue en curso tras «Me encuentro mal»')
  comprobar((await perfilBD()).urgencias?.includes('mareo'), 'La señal no se guarda en el perfil')
  await pulsar('Entendido')
  await ver('Hoy no entrenes') // también en la tarjeta de Inicio
  await revisarAqui('inicio con una señal marcada')
  // Se desmarca en Perfil → Salud y vuelve la rutina.
  await pulsar('Ir a Salud')
  await pulsar('Mareo o desmayo')
  await esperar(300)
  comprobar(!(await perfilBD()).urgencias?.length, 'No se desmarca la señal en Perfil → Salud')
  await pestana('Inicio')
  await ver('Te toca')
  // Mi plan: la cola y el cambio a días fijos (y vuelta).
  await pestana('Rutina')
  await ver('Cómo va tu rutina')
  await ver('La cola')
  await ver('Siguiente')
  await revisarAqui('mi plan en cola')
  await pulsar('Días fijos')
  await esperar(300)
  comprobar((await perfilBD()).modoRutina === 'dias', '«Días fijos» no se guarda')
  await ver('Toca uno para verlo')
  await pulsar('En orden')
  await esperar(300)
  comprobar((await perfilBD()).modoRutina === 'cola', '«En orden» no se guarda')
})

escenario('revisión de la semana: todo bien, una molestia que va peor con su «Deshacer», «no quiero» y cardio', async () => {
  await deCero('2026-10-13T05:20:00')
  await alta({ cola: true })
  // Sin molestias: «Todo bien» la cierra de un toque.
  await t('pulsarSel', '[aria-label="Ajustes"]')
  await ver('Tu rutina y tu salud')
  await pulsar('Revisión de la semana')
  await ver('¿Qué tal estás?')
  await revisarAqui('revisión sin molestias')
  await pulsar('Todo bien')
  await ver('Apuntado. ¡Buena semana!')
  comprobar((await tabla('revisiones')).length === 1, 'La revisión «Todo bien» no se guarda')
  await pulsar(/^Vale$/)
  // Con una molestia en la rodilla que va peor: cambia los entrenos y se puede deshacer.
  const p = await perfilBD()
  await meter('perfil', [{ ...p, dolores: [{ zona: 'rodillas', cuanto: 'poco', cuando: 'aveces', desde: 'dias', inicio: '2026-10-13' }] }])
  await recargar()
  await t('pulsarSel', '[aria-label="Ajustes"]')
  await pulsar('Revisión de la semana')
  await ver('Lo que te dolía')
  await pulsar(/^Peor$/)
  await pulsar('No, nada nuevo')
  await pulsar('Guardar revisión')
  await ver('Tu semana, ajustada')
  await revisarAqui('revisión: tu semana, ajustada')
  const [rev] = (await tabla('revisiones')).filter(r => r.respuestas.length)
  comprobar(rev?.cambios.length > 0, 'Una molestia que va peor no cambia nada de la rutina')
  comprobar((await perfilBD()).dolores[0].cuanto === 'regular', 'La molestia no sube un nivel al ir peor')
  await pulsar('Deshacer')
  await ver('Deshecho')
  await esperar(300)
  const otra = (await tabla('revisiones')).find(r => r.id === rev.id)
  comprobar(otra.cambios.some(c => c.deshecho), '«Deshacer» no marca el cambio como deshecho')
  await pulsar(/^Vale$/)
  // «Lo que no quieres hacer» desde Ajustes.
  await pulsar('Lo que no quieres hacer')
  await ver('¿Qué no quieres hacer?')
  await pulsar('Poleas', '.sheet')
  await pulsar(/^Guardar$/, '.sheet')
  await ver('no saldrá en tu rutina')
  comprobar((await perfilBD()).noQuiero?.includes('poleas'), '«No quiero» no se guarda')
  // Cardio en «Hoy en números»: se apunta desde la tarjeta.
  await meter('perfil', [{ ...(await perfilBD()), cardioMin: 60, cardioCuando: 'despues', cardioTipos: ['bici'] }])
  await recargar()
  await ver('Cardio esta semana')
  await ver(/Y al acabar/)
  await js(`[...document.querySelectorAll('button.kpi')].find(b => /cardio esta semana/i.test(b.innerText))?.click()`)
  await ver('Apuntar cardio')
  await pulsar(/^Guardar$/, '.sheet')
  await ver('Apuntado:')
  const [dia] = await tabla('pasos')
  comprobar(dia?.cardio?.[0]?.tipo === 'bici' && dia.cardio[0].min === 20, 'El cardio no se apunta: ' + JSON.stringify(dia))
  await ver('20/ 60 min')
})
